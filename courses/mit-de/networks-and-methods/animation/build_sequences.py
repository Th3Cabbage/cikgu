"""Render the Electrical Networks and Solution Methods animations with ManimGL and package them for the browser guide.

    .venv\\Scripts\\python.exe courses\\controls\\linearization\\animation\\build_sequences.py [--only ID ...] [--force] [--no-render] [--jobs 1]

Needs the render dependencies in courses/mit-de/networks-and-methods/requirements-render.txt (ManimGL 1.7.2, matplotlib,
imageio-ffmpeg; audioop-lts on Python 3.13+). No LaTeX: formulas are typeset with matplotlib
mathtext (see ctl_common.py). FFmpeg is the binary bundled with imageio-ffmpeg; it is written into
a generated ManimGL config (masters/render_config.yml, file_writer.ffmpeg_bin) and used for cutting.

For every sequence in control_specs.SEQUENCES:
 1. Render the master video of its scene (sequence_scenes.py) offscreen at 1280x720, 30 fps,
    into courses/mit-de/networks-and-methods/animation/masters, unless the stored stamp shows it is current (--force always
    re-renders; --no-render never does). The scene writes <Scene>.boundaries.json: the frame
    index where the opening still ends and where each step ends (after a short hold).
 2. Cut one clip per step at exact frame boundaries. Clip k covers master frames
    [b[k-1] - 1, b[k]): it starts on the last frame of the previous stable state and ends on
    the first fully settled frame of the new one, so playback never jumps.
 3. Extract stable stills: state 0 is the first frame of clip 1 and state k is the last frame
    of clip k (decoded from the clips themselves with the BT.601 matrix they are tagged with).
 4. Count every clip's decoded frames and write courses/mit-de/networks-and-methods/dist/animations/manifest.json.
"""
import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
CONTROL = os.path.dirname(HERE)
PROJECT = os.path.dirname(os.path.dirname(os.path.dirname(CONTROL)))
VENV = os.path.join(PROJECT, ".venv")
MANIMGL = os.path.join(VENV, "Scripts", "manimgl.exe") if os.name == "nt" else os.path.join(VENV, "bin", "manimgl")
SCENES_PY = os.path.join(HERE, "sequence_scenes.py")
COMMON_PY = os.path.join(HERE, "ctl_common.py")
MASTERS = os.path.join(HERE, "masters")
CONFIG = os.path.join(MASTERS, "render_config.yml")
OUT = os.path.join(CONTROL, "dist", "animations")
FPS = 30
WIDTH, HEIGHT = 1280, 720
BG = "#0B0F17"

sys.path.insert(0, HERE)
from control_specs import RELATIONS, SECTION_SEQUENCES, SEQUENCES  # noqa: E402

COLOR_TAGS = ["-colorspace", "smpte170m", "-color_primaries", "smpte170m", "-color_trc", "smpte170m",
              "-color_range", "tv"]


def ffmpeg_exe():
    import imageio_ffmpeg
    return imageio_ffmpeg.get_ffmpeg_exe()


FFMPEG = None


def run(cmd, **kw):
    res = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if res.returncode != 0:
        raise RuntimeError(f"command failed ({res.returncode}): {' '.join(cmd)}\n{res.stderr[-3000:]}")
    return res


def write_config():
    os.makedirs(MASTERS, exist_ok=True)
    text = ("# Generated by build_sequences.py; machine-specific (FFmpeg path). Do not edit.\n"
            "camera:\n"
            f"  resolution: \"({WIDTH}, {HEIGHT})\"\n"
            f"  background_color: \"{BG}\"\n"
            f"  fps: {FPS}\n"
            "file_writer:\n"
            f"  ffmpeg_bin: '{FFMPEG}'\n")
    with open(CONFIG, "w", encoding="utf-8") as f:
        f.write(text)


def stamp_for(scene):
    """Hash of everything that changes the pixels: scene code, shared helpers, resolution/fps and,
    from the specs, only what the scenes read (ids, step counts, relations). Editing explanation
    text does not force a re-render."""
    h = hashlib.sha256()
    for p in (SCENES_PY, COMMON_PY):
        with open(p, "rb") as f:
            h.update(f.read())
    visual = [[q["id"], q["scene"], [st["relation"] for st in q["steps"]]] for q in SEQUENCES]
    h.update(json.dumps([visual, sorted(RELATIONS), WIDTH, HEIGHT, FPS, BG]).encode())
    h.update(scene.encode())
    return h.hexdigest()


def probe(path):
    """Decode the whole clip with FFmpeg and report frame count, codec, size and pixel format."""
    res = subprocess.run([FFMPEG, "-hide_banner", "-i", path, "-map", "0:v:0", "-f", "null", "-"],
                         capture_output=True, text=True)
    if res.returncode != 0:
        raise RuntimeError(f"could not decode {path}\n{res.stderr[-1500:]}")
    err = res.stderr
    frames = [int(m) for m in re.findall(r"frame=\s*(\d+)", err)]
    vs = re.search(r"Stream #0:0[^\n]*Video: ([^\n]*)", err)   # first match: the input stream
    line = vs.group(1) if vs else ""
    codec = re.match(r"(\w+)", line)
    size = re.search(r"\b(\d{2,5})x(\d{2,5})\b", line)
    return {"frames": frames[-1] if frames else 0, "codec": codec.group(1) if codec else "?",
            "size": f"{size.group(1)}x{size.group(2)}" if size else "?", "stream": line}


def render_master(seq, env, force, no_render, log):
    scene = seq["scene"]
    master = os.path.join(MASTERS, scene + ".mp4")
    bfile = os.path.join(MASTERS, scene + ".boundaries.json")
    sfile = os.path.join(MASTERS, scene + ".stamp")
    stamp = stamp_for(scene)
    current = (os.path.exists(master) and os.path.exists(bfile) and os.path.exists(sfile)
               and open(sfile, encoding="ascii").read().strip() == stamp)
    if no_render or (current and not force):
        if not current:
            log(f"  WARNING {scene}: master is not current for this source (--no-render)")
        return master, bfile, 0.0
    t0 = time.time()
    for p in (bfile, sfile):
        if os.path.exists(p):
            os.remove(p)
    cmd = [MANIMGL, SCENES_PY, scene, "-w", "--config_file", CONFIG, "--video_dir", MASTERS]
    log(f"  {scene}: rendering ...")
    res = subprocess.run(cmd, cwd=HERE, env=env, capture_output=True, text=True)
    with open(os.path.join(MASTERS, scene + ".render.log"), "w", encoding="utf-8") as f:
        f.write(res.stdout + "\n--- stderr ---\n" + res.stderr)
    if res.returncode != 0 or not os.path.exists(bfile):
        raise RuntimeError(f"{scene} failed to render; see courses/mit-de/networks-and-methods/animation/masters/{scene}.render.log\n"
                           f"{res.stderr[-2500:]}")
    with open(sfile, "w", encoding="ascii") as f:
        f.write(stamp)
    dt = time.time() - t0
    log(f"  {scene}: rendered in {dt:.1f}s")
    return master, bfile, dt


def cut(master, a, b, out):
    run([FFMPEG, "-y", "-v", "error", "-i", master,
         "-vf", f"trim=start_frame={a}:end_frame={b},setpts=PTS-STARTPTS,"
                "setparams=colorspace=smpte170m:color_primaries=smpte170m:color_trc=smpte170m:range=tv",
         "-an", "-c:v", "libx264", "-preset", "slow", "-crf", "20", "-pix_fmt", "yuv420p",
         "-r", str(FPS), "-g", "9999", *COLOR_TAGS, "-movflags", "+faststart", out])


def still(clip, index, out):
    run([FFMPEG, "-y", "-v", "error", "-i", clip,
         "-vf", f"select=eq(n\\,{index}),scale=in_color_matrix=bt601:in_range=tv:out_range=pc,format=yuvj444p",
         "-frames:v", "1", "-q:v", "3", out])


def package(seq, master, bfile, render_s, log):
    sid = seq["id"]
    with open(bfile, encoding="utf-8") as f:
        info = json.load(f)
    b = info["boundaries"]
    n = len(seq["steps"])
    if len(b) != n + 1:
        raise RuntimeError(f"{sid}: {len(b) - 1} recorded steps, spec has {n}")
    mp = probe(master)
    if mp["frames"] != info["frames"]:
        raise RuntimeError(f"{sid}: master has {mp['frames']} frames, scene emitted {info['frames']}")
    if b[-1] != info["frames"]:
        raise RuntimeError(f"{sid}: last boundary {b[-1]} is not the final frame count {info['frames']}")
    out_dir = os.path.join(OUT, sid)
    os.makedirs(out_dir, exist_ok=True)
    for name in os.listdir(out_dir):
        os.remove(os.path.join(out_dir, name))
    rel = lambda name: f"animations/{sid}/{name}"  # noqa: E731
    steps = []
    for k in range(1, n + 1):
        a, e = b[k - 1] - 1, b[k]
        clip = os.path.join(out_dir, f"step-{k:02d}.mp4")
        cut(master, a, e, clip)
        p = probe(clip)
        if p["frames"] != e - a:
            raise RuntimeError(f"{sid} step {k}: clip has {p['frames']} frames, expected {e - a}")
        if k == 1:
            still(clip, 0, os.path.join(out_dir, "state-00.jpg"))
        still(clip, p["frames"] - 1, os.path.join(out_dir, f"state-{k:02d}.jpg"))
        st = seq["steps"][k - 1]
        steps.append({
            "index": k,
            "title": st["title"],
            "relation": st["relation"],
            "relationLabel": RELATIONS[st["relation"]],
            "tex": st["tex"],
            "explanation": st["explanation"],
            "initialFrame": rel(f"state-{k - 1:02d}.jpg"),
            "finalFrame": rel(f"state-{k:02d}.jpg"),
            "transition": {
                "src": rel(f"step-{k:02d}.mp4"),
                "duration": round(p["frames"] / FPS, 4),
                "frames": p["frames"],
                "masterFrames": [a, e],
                "bytes": os.path.getsize(clip),
                "codec": p["codec"],
            },
        })
    entry = {
        "id": sid,
        "scene": seq["scene"],
        "section": seq["section"],
        "title": seq["title"],
        "summary": seq["summary"],
        "initial": {**seq["initial"], "frame": rel("state-00.jpg")},
        "steps": steps,
        "totalDuration": round(sum(s["transition"]["duration"] for s in steps), 3),
        "masterFrames": info["frames"],
        "renderSeconds": round(render_s, 1),
    }
    log(f"  {sid}: {n} clips, {entry['totalDuration']:.2f}s of transitions")
    return entry


def main():
    global FFMPEG
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--only", nargs="*", help="sequence ids to rebuild (others are kept from the manifest)")
    ap.add_argument("--force", action="store_true", help="re-render masters even if current")
    ap.add_argument("--no-render", action="store_true", help="never render; only cut existing masters")
    ap.add_argument("--jobs", type=int, default=1, help="masters rendered in parallel (default 1: parallel ManimGL Text renders were seen to collide on shared temp SVG files)")
    args = ap.parse_args()

    FFMPEG = ffmpeg_exe()
    write_config()
    os.makedirs(OUT, exist_ok=True)
    env = dict(os.environ)
    env["PATH"] = os.path.dirname(FFMPEG) + os.pathsep + env.get("PATH", "")
    env["PYTHONWARNINGS"] = "ignore"
    lines = []

    def log(s):
        print(s, flush=True)
        lines.append(s)

    manifest_path = os.path.join(OUT, "manifest.json")
    old = {}
    if args.only and os.path.exists(manifest_path):
        with open(manifest_path, encoding="utf-8") as f:
            old = {s["id"]: s for s in json.load(f)["sequences"]}
    unknown = set(args.only or []) - {s["id"] for s in SEQUENCES}
    if unknown:
        raise SystemExit(f"unknown sequence ids: {sorted(unknown)}")
    todo = [s for s in SEQUENCES if not args.only or s["id"] in args.only]
    for s in SEQUENCES:
        if s not in todo and s["id"] not in old:
            raise SystemExit(f"{s['id']} is not in the existing manifest; build it too")
    t0 = time.time()
    with ThreadPoolExecutor(max_workers=max(1, args.jobs)) as pool:
        renders = {s["id"]: pool.submit(render_master, s, env, args.force, args.no_render, log) for s in todo}
        results = {sid: fut.result() for sid, fut in renders.items()}
    entries = []
    for seq in SEQUENCES:
        if seq["id"] in results:
            log(f"[{seq['id']}]")
            entries.append(package(seq, *results[seq["id"]], log))
        else:
            entries.append(old[seq["id"]])

    manifest = {
        "version": 1,
        "width": WIDTH,
        "height": HEIGHT,
        "fps": FPS,
        "relations": RELATIONS,
        "sections": {str(k): v for k, v in sorted(SECTION_SEQUENCES.items())},
        "sequences": entries,
    }
    with open(manifest_path, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=1, ensure_ascii=False)
    total = sum(os.path.getsize(os.path.join(dp, fn)) for dp, _, fns in os.walk(OUT) for fn in fns)
    log(f"manifest: {len(entries)} sequences, {sum(len(e['steps']) for e in entries)} steps, "
        f"{total / 1e6:.2f} MB in dist/animations, built in {time.time() - t0:.1f}s")


if __name__ == "__main__":
    main()
